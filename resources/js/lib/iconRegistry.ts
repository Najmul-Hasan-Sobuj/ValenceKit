export const allSupportedIconNames: string[] = Object.keys(iconRegistry).sort();

/**
 * Resolve an icon component safely from the supported registry.
 * Falls back to HelpCircle (or provided fallback) for unknown or legacy names.
 */
export function getCategoryIcon(
    name: string | null | undefined,
    defaultFallback: Component = fallbackIcon,
): Component {
    if (!name) {
        return defaultFallback;
    }

    return iconRegistry[name] || defaultFallback;
}
